#!/usr/bin/env node
// Regenerates src/domain/catalog/v2/categoryTrustMap.ts from the production
// category trust audit (J1D-CAT-02). Only SEMANTIC_STRONG / SEMANTIC_WEAK
// categories can name a product's meaningful category; every other class
// (NAVIGATION root, CAMPAIGN, LEGACY, UNKNOWN/test) is left out on purpose.
//   node scripts/catalog-v2/generate-category-trust-map.mjs [trust-map.csv]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const source = process.argv[2] ?? 'docs/audits/product-intelligence-exploration/inputs/category_trust_map(1).csv';
const text = readFileSync(resolve(source), 'utf8');

function parseCsv(input) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let index = 0; index < input.length; index += 1) {
    const char = input[index];
    if (quoted) {
      if (char === '"' && input[index + 1] === '"') { field += '"'; index += 1; }
      else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') { row.push(field); field = ''; }
    else if (char === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (char !== '\r') field += char;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(text);
const column = (name) => header.indexOf(name);
const entries = rows
  .filter((row) => row.length === header.length)
  .map((row) => ({ id: Number(row[column('categoryId')]), trustClass: row[column('trustClass')], name: row[column('categoryName')] }))
  .filter((entry) => entry.trustClass === 'SEMANTIC_STRONG' || entry.trustClass === 'SEMANTIC_WEAK')
  .sort((left, right) => left.id - right.id);

const sourceLabel = source.split(String.fromCharCode(92)).join('/');
const sourceSha256 = createHash('sha256').update(text).digest('hex');
const lines = entries.map((entry) => `  [${entry.id}, '${entry.trustClass}'], // ${entry.name.replace(/\*\//gu, '')}`);
writeFileSync(resolve('src/domain/catalog/v2/categoryTrustMap.ts'), `// GENERATED by scripts/catalog-v2/generate-category-trust-map.mjs — do not edit by hand.
// Source: ${sourceLabel} (sha256 ${sourceSha256}).
// Keys are PRODUCTION PrestaShop category ids from the category trust audit.

export const CATEGORY_TRUST_MAP_VERSION = 'category-trust-v1+${sourceSha256.slice(0, 12)}';

export type MeaningfulCategoryTrust = 'SEMANTIC_STRONG' | 'SEMANTIC_WEAK';

export const CATEGORY_TRUST_BY_ID: ReadonlyMap<number, MeaningfulCategoryTrust> = new Map<number, MeaningfulCategoryTrust>([
${lines.join('\n')}
]);
`);
console.log(`categoryTrustMap.ts: ${entries.length} meaningful categories`);
